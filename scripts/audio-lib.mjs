import {createHash} from 'node:crypto';
import {appendFileSync, existsSync, readFileSync, writeFileSync} from 'node:fs';

/** Owner-provided: the plan the account is on (licence condition). Override with ELEVENLABS_PLAN. */
export const PLAN = process.env.ELEVENLABS_PLAN || 'Creator';

/** Parse `--name value` options and `--bool` switches out of argv. Returns {pos, opts, bools}. */
export const parseArgs = (argv, valueFlags, boolFlags = []) => {
  /** @type {string[]} */
  const pos = [];
  /** @type {Record<string, string>} */
  const opts = {};
  /** @type {Record<string, boolean>} */
  const bools = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (valueFlags.includes(a)) {
      const v = argv[i + 1];
      if (v === undefined || v.startsWith('--')) throw new Error(`${a} needs a value.`);
      opts[a.slice(2)] = v;
      i++;
    } else if (boolFlags.includes(a)) bools[a.slice(2)] = true;
    else if (a.startsWith('--')) throw new Error(`Unknown option ${a}.`);
    else pos.push(a);
  }
  return {pos, opts, bools};
};

/** Names become file names: letters, digits, dash, underscore, dot (no slashes). */
export const validName = (s) => /^[A-Za-z0-9][A-Za-z0-9._-]*$/.test(s);

/**
 * Prompts must be instrumental and name no artist, song, label or lyrics (licence condition 3).
 * A simple pattern check, not a guarantee: returns the matched text or null.
 */
const BANNED = [
  /\b(?:in the style of|style of|sounds? like|similar to|reminiscent of|inspired by|cover of|remix of|version of)\b/i,
  /\b(?:by|feat\.?|featuring|ft\.?)\s+[A-Z][\w'-]+/,
  /\b(?:records|recordings|music group|publishing)\b/i,
  /\b(?:lyrics?|vocals?|singing|singer|sung|rap(?:ping)?|choir|lyrical)\b/i,
  /["“”].+["“”]/,
];
export const bannedPattern = (prompt) => {
  for (const re of BANNED) {
    const m = prompt.match(re);
    if (m) return m[0];
  }
  return null;
};

export const sha256 = (file) => createHash('sha256').update(readFileSync(file)).digest('hex');

const LOG_HEADER = `# Audio generation log

> **Generated by \`yarn music\` and \`yarn sfx\`. Do not hand-edit.**
> This is our record of every ElevenLabs music and sound-effect file: when it was made, on which plan,
> with which prompt, and its sha256. It is the evidence we use to dispute a Content ID claim and to prove
> the plan in effect when the audio was created (see \`brand/research/music-licensing.md\`). Edited or
> back-filled entries would make it worthless as proof. Append-only; commit it with the video.
`;

/** Append one entry to src/videos/<slug>/audio-log.md (creates it with the header). */
export const appendLog = ({dir, endpoint, model, prompt, length, output, file, kind, plan = PLAN, extra = {}}) => {
  const log = `${dir}/audio-log.md`;
  if (!existsSync(log)) writeFileSync(log, LOG_HEADER);
  const entry = [
    '',
    `## ${new Date().toISOString()} · ${kind} · ${output}`,
    '',
    `- Plan: ${plan} (owner-provided)`,
    `- Endpoint: ${endpoint}`,
    `- Model: ${model}`,
    `- Length: ${length}`,
    ...Object.entries(extra).map(([k, v]) => `- ${k}: ${v}`),
    `- Output: ${output}`,
    `- sha256: ${sha256(file)}`,
    `- Prompt: ${JSON.stringify(prompt)}`,
    '',
  ].join('\n');
  appendFileSync(log, entry);
  return log;
};

/** POST JSON and return the audio bytes. Exits on an API error (message only, never the key). */
export const postAudio = async (url, key, body) => {
  const res = await fetch(url, {
    method: 'POST',
    headers: {'xi-api-key': key, 'Content-Type': 'application/json'},
    body: JSON.stringify(body),
  });
  if (!res.ok) {
    console.error(`ElevenLabs ${res.status}: ${await res.text()}`);
    process.exit(1);
  }
  return Buffer.from(await res.arrayBuffer());
};

/** Print the request that would be sent (no key). */
export const printDryRun = (method, url, body) => {
  console.log(`DRY RUN: nothing sent, nothing written.\n${method} ${url}\nxi-api-key: <from .env, not shown>`);
  console.log(JSON.stringify(body, null, 2));
};
