// Self-made rumble-strip roar heard from inside a car: a deterministic synth (no API, no cost).
//
// usage: yarn sfx:rumble <slug> [--name roar-synth] [--out <file>] [--seconds 4] [--lufs -15]
//
// Options: --pitch (thump pitch multiplier), --reso (body resonance Hz), --cutoff (final low-pass Hz),
// --drive (tanh saturation amount, 0 = off), --attack (onset click level). Defaults give roar-synth.
// Model: grooves 12 in apart at 60 mph = 88 impacts/s. Each impact is a short damped low thump
// (60-110 Hz, ~15 ms decay) with seeded level (+-25%) and timing (+-6% of the period) jitter, run
// through a ~110 Hz body resonance, plus a bed of low-passed (<300 Hz) tire/road noise with a slow
// swell. Everything is low-passed at ~500 Hz, so nothing above about 1 kHz (no buzz, no rattle).
// Mono 44.1 kHz, short fade-in/out, scaled to the target integrated loudness (default -15 LUFS) and
// checked to stay under -1.5 dBTP (no limiter in the bundled ffmpeg, so it fails rather than clips), encoded with Remotion's bundled ffmpeg (libmp3lame, 128k). Same samples every run.
// Default output is an audition: out/<slug>/raw/sfx/<name>.mp3. It never touches src/. Not logged in
// audio-log.md (nothing generated by a service).
import {spawnSync} from 'node:child_process';
import {mkdirSync, mkdtempSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname, join} from 'node:path';

const usage = 'yarn sfx:rumble <slug> [--name roar-synth] [--out <file>] [--seconds 4] [--lufs -15]\n  [--pitch 1] [--reso 110] [--cutoff 500] [--drive 0] [--attack 0]';
const fail = (msg) => {
  console.error(`${msg}\nusage: ${usage}`);
  process.exit(1);
};
const argv = process.argv.slice(2);
if (argv.includes('--help') || argv.includes('-h')) {
  console.log(`${usage}\n\n  Default output: out/<slug>/raw/sfx/<name>.mp3 (audition; never writes into src/).`);
  process.exit(0);
}
const opt = {name: 'roar-synth', out: '', seconds: '4', lufs: '-15', pitch: '1', reso: '110', cutoff: '500', drive: '0', attack: '0'};
const pos = [];
for (let i = 0; i < argv.length; i++) {
  if (argv[i].startsWith('--') && argv[i].slice(2) in opt) opt[argv[i].slice(2)] = argv[++i] ?? '';
  else pos.push(argv[i]);
}
const [slug] = pos;
const re = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;
if (!slug || pos.length > 1 || !re.test(slug) || !re.test(opt.name)) fail('expected exactly one valid <slug> and a valid --name');
const seconds = Number(opt.seconds), lufs = Number(opt.lufs);
if (!(seconds > 0.5 && seconds <= 60) || !(lufs < 0 && lufs > -40)) fail('invalid --seconds or --lufs');
const pitch = Number(opt.pitch), reso = Number(opt.reso), cutoff = Number(opt.cutoff), drive = Number(opt.drive), attack = Number(opt.attack);
if (![pitch, reso, cutoff, drive, attack].every(Number.isFinite) || pitch <= 0 || reso <= 0 || cutoff < 100 || cutoff > 2000 || drive < 0 || attack < 0) fail('invalid --pitch/--reso/--cutoff/--drive/--attack (cutoff 100-2000)');
const outFile = opt.out || join('out', slug, 'raw', 'sfx', `${opt.name}.mp3`);

const sr = 44100, n = Math.round(sr * seconds);
let seed = 88;
const rnd = () => ((seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff) * 2 - 1;

// Impact train. --pitch scales the thump pitch, --attack adds a noise click per hit.
const imp = new Float64Array(n), period = sr / 88;
for (let k = 0; ; k++) {
  const start = k * period + rnd() * 0.06 * period;
  if (start >= n) break;
  const level = 1 + rnd() * 0.25, f = (70 + rnd() * 10) * pitch;
  const i0 = Math.max(0, Math.ceil(start));
  for (let i = i0; i < Math.min(n, i0 + 900); i++) {
    const t = (i - start) / sr;
    imp[i] += level * (Math.sin(2 * Math.PI * f * t) * Math.exp(-t / 0.012) + 0.4 * Math.sin(2 * Math.PI * 110 * pitch * t) * Math.exp(-t / 0.007));
    if (attack > 0 && i - i0 < 220) imp[i] += attack * rnd() * Math.exp(-t / 0.0012); // sharp onset click
  }
}
// Body resonance (two-pole, ~110 Hz) mixed with the dry thump.
const res = (x, f0, r) => {
  const w = 2 * Math.PI * f0 / sr, a1 = -2 * r * Math.cos(w), a2 = r * r, y = new Float64Array(x.length);
  for (let i = 0; i < x.length; i++) y[i] = (1 - r) * x[i] - a1 * (y[i - 1] ?? 0) - a2 * (y[i - 2] ?? 0);
  return y;
};
const lp = (x, fc, passes = 1) => {
  const a = 1 - Math.exp(-2 * Math.PI * fc / sr);
  let y = Float64Array.from(x);
  for (let p = 0; p < passes; p++) { let s = 0; for (let i = 0; i < y.length; i++) y[i] = s += a * (y[i] - s); }
  return y;
};
const body = res(imp, reso, 0.995);
let noise = new Float64Array(n);
for (let i = 0; i < n; i++) noise[i] = rnd();
noise = lp(noise, 300, 2);
const x = new Float64Array(n);
for (let i = 0; i < n; i++) {
  const swell = 1 + 0.15 * Math.sin(2 * Math.PI * 1.7 * i / sr);
  x[i] = imp[i] * 0.6 + body[i] * 8 + noise[i] * 9 * swell;
}
if (drive > 0) { // soft saturation: grit and growl; the low-pass below keeps the harmonics under --cutoff
  let xp = 0;
  for (let i = 0; i < n; i++) xp = Math.max(xp, Math.abs(x[i]));
  for (let i = 0; i < n; i++) x[i] = Math.tanh((drive * x[i]) / xp);
}
const y = lp(x, cutoff, 2);
// Normalise to a 0.3 peak so the draft measurement is well above the loudness gate.
let pk = 0;
for (let i = 0; i < n; i++) pk = Math.max(pk, Math.abs(y[i]));
for (let i = 0; i < n; i++) y[i] *= 0.3 / pk;
// Short fades.
const fade = Math.round(0.12 * sr);
for (let i = 0; i < fade; i++) { const g = Math.sin(0.5 * Math.PI * i / fade); y[i] *= g; y[n - 1 - i] *= g; }

const writeWav = (file, gain) => {
  const pcm = new Int16Array(n);
  for (let i = 0; i < n; i++) pcm[i] = Math.round(Math.max(-1, Math.min(1, y[i] * gain)) * 32767);
  const data = Buffer.from(pcm.buffer), h = Buffer.alloc(44);
  h.write('RIFF', 0); h.writeUInt32LE(36 + data.length, 4); h.write('WAVEfmt ', 8);
  h.writeUInt32LE(16, 16); h.writeUInt16LE(1, 20); h.writeUInt16LE(1, 22); h.writeUInt32LE(sr, 24);
  h.writeUInt32LE(sr * 2, 28); h.writeUInt16LE(2, 32); h.writeUInt16LE(16, 34); h.write('data', 36); h.writeUInt32LE(data.length, 40);
  writeFileSync(file, Buffer.concat([h, data]));
};
const ff = (args) => spawnSync('npx', ['remotion', 'ffmpeg', '-hide_banner', '-nostdin', '-y', ...args], {encoding: 'utf8'});

const tmp = mkdtempSync(join(tmpdir(), 'sfx-rumble-'));
try {
  const wav = join(tmp, 'rumble.wav');
  writeWav(wav, 1);
  // Measure integrated loudness of the unit-scaled draft, then compute the gain to hit the target.
  const meas = (file) => {
    const m = ff(['-i', file, '-af', 'loudnorm=I=-15:TP=-1.5:print_format=json', '-f', 'null', '-']);
    const j = /\{[^{}]*"input_i"[^{}]*\}/.exec(m.stderr || '');
    if (!j) fail(`could not measure loudness:\n${(m.stderr || '').slice(-800)}`);
    const o = JSON.parse(j[0]);
    return {i: Number(o.input_i), tp: Number(o.input_tp)};
  };
  // The bundled ffmpeg has no alimiter, so scale by gain only; the steady roar has a low crest factor.
  const d = meas(wav);
  const gain = 10 ** ((lufs - d.i) / 20);
  if (d.tp + (lufs - d.i) > -1.5) fail(`peak would exceed -1.5 dBTP at ${lufs} LUFS (${(d.tp + lufs - d.i).toFixed(2)}); lower --lufs`);
  writeWav(wav, gain);
  mkdirSync(dirname(outFile), {recursive: true});
  const r = ff(['-i', wav, '-c:a', 'libmp3lame', '-b:a', '128k', outFile]);
  if (r.status !== 0) fail(`ffmpeg failed:\n${(r.stderr || '').slice(-1500)}`);
  console.log(`wrote ${outFile} (target ${lufs} LUFS)`);
} finally {
  rmSync(tmp, {recursive: true, force: true});
}
