// Self-made EV motor whine under regenerative braking: a deterministic synth (no API, no cost).
//
// usage: yarn sfx:whine <slug> [--name whine] [--out <file>] [--from 900] [--to 200] [--seconds 3]
//        [--lufs -18] [--noise 0.3] [--curve 1.6]
//
// Model: a clean tone gliding DOWN from --from Hz to --to Hz over --seconds, plus two inharmonic
// partials (x2.76 at 35%, x5.4 at 12%, phase-accumulated so the glide has no zipper noise), a faint
// slow 6 Hz wobble in level, and a bed of low-passed (<350 Hz) road/tire noise at --noise (0..1,
// relative level, 0 = off). --curve shapes the glide: f(u) = to + (from-to) * (1-u)^curve, so 1 is
// linear in Hz, >1 drops fast then settles (default 1.6), <1 holds then drops. The whine gets quieter
// as the car slows. Whole mix is low-passed at 4 kHz (smooth, no buzz, no rattle).
// Mono 44.1 kHz, 0.15 s fade-in/out, scaled to the target integrated loudness (default -18 LUFS) and
// checked to stay under -1.5 dBTP (the bundled ffmpeg has no limiter, so it fails rather than clips),
// encoded with Remotion's bundled ffmpeg (libmp3lame, 128k). Same samples every run.
// Default output is an audition: out/<slug>/raw/sfx/<name>.mp3. It never touches src/. Not logged in
// audio-log.md (nothing generated by a service).
import {spawnSync} from 'node:child_process';
import {mkdirSync, mkdtempSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname, join} from 'node:path';

const usage = 'yarn sfx:whine <slug> [--name whine] [--out <file>] [--from 900] [--to 200] [--seconds 3]\n  [--lufs -18] [--noise 0.3] [--curve 1.6]';
const fail = (msg) => {
  console.error(`${msg}\nusage: ${usage}`);
  process.exit(1);
};
const argv = process.argv.slice(2);
if (argv.includes('--help') || argv.includes('-h')) {
  console.log(`${usage}\n\n  Default output: out/<slug>/raw/sfx/<name>.mp3 (audition; never writes into src/).`);
  process.exit(0);
}
const opt = {name: 'whine', out: '', from: '900', to: '200', seconds: '3', lufs: '-18', noise: '0.3', curve: '1.6'};
const pos = [];
for (let i = 0; i < argv.length; i++) {
  if (argv[i].startsWith('--') && argv[i].slice(2) in opt) opt[argv[i].slice(2)] = argv[++i] ?? '';
  else pos.push(argv[i]);
}
const [slug] = pos;
const re = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;
if (!slug || pos.length > 1 || !re.test(slug) || !re.test(opt.name)) fail('expected exactly one valid <slug> and a valid --name');
const seconds = Number(opt.seconds), lufs = Number(opt.lufs);
const f0 = Number(opt.from), f1 = Number(opt.to), noiseAmt = Number(opt.noise), curve = Number(opt.curve);
if (!(seconds > 0.5 && seconds <= 60) || !(lufs < 0 && lufs > -40)) fail('invalid --seconds or --lufs');
if (![f0, f1, noiseAmt, curve].every(Number.isFinite) || f0 < 50 || f0 > 3000 || f1 < 50 || f1 > 3000 || noiseAmt < 0 || noiseAmt > 1 || curve <= 0) fail('invalid --from/--to (50-3000 Hz), --noise (0-1) or --curve (>0)');
const outFile = opt.out || join('out', slug, 'raw', 'sfx', `${opt.name}.mp3`);

const sr = 44100, n = Math.round(sr * seconds);
let seed = 7;
const rnd = () => ((seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff) * 2 - 1;
const lp = (x, fc, passes = 1) => {
  const a = 1 - Math.exp(-2 * Math.PI * fc / sr);
  const y = Float64Array.from(x);
  for (let p = 0; p < passes; p++) { let s = 0; for (let i = 0; i < y.length; i++) y[i] = s += a * (y[i] - s); }
  return y;
};

const tone = new Float64Array(n);
let ph = 0;
for (let i = 0; i < n; i++) {
  const u = i / (n - 1), f = f1 + (f0 - f1) * (1 - u) ** curve;
  ph += 2 * Math.PI * f / sr;
  const level = (0.45 + 0.55 * (f1 === f0 ? 1 : (f - Math.min(f0, f1)) / Math.abs(f0 - f1))) * (1 + 0.04 * Math.sin(2 * Math.PI * 6 * i / sr));
  tone[i] = level * (Math.sin(ph) + 0.35 * Math.sin(2.76 * ph) + 0.12 * Math.sin(5.4 * ph));
}
let road = new Float64Array(n);
for (let i = 0; i < n; i++) road[i] = rnd();
road = lp(road, 350, 2);
let rp = 0;
for (let i = 0; i < n; i++) rp = Math.max(rp, Math.abs(road[i]));
let tp = 0;
for (let i = 0; i < n; i++) tp = Math.max(tp, Math.abs(tone[i]));
const y = new Float64Array(n);
for (let i = 0; i < n; i++) y[i] = tone[i] / tp + (noiseAmt * road[i]) / rp;
const z = lp(y, 4000, 2);
let pk = 0;
for (let i = 0; i < n; i++) pk = Math.max(pk, Math.abs(z[i]));
for (let i = 0; i < n; i++) z[i] *= 0.3 / pk;
const fade = Math.round(0.15 * sr);
for (let i = 0; i < fade; i++) { const g = Math.sin(0.5 * Math.PI * i / fade); z[i] *= g; z[n - 1 - i] *= g; }

const writeWav = (file, gain) => {
  const pcm = new Int16Array(n);
  for (let i = 0; i < n; i++) pcm[i] = Math.round(Math.max(-1, Math.min(1, z[i] * gain)) * 32767);
  const data = Buffer.from(pcm.buffer), h = Buffer.alloc(44);
  h.write('RIFF', 0); h.writeUInt32LE(36 + data.length, 4); h.write('WAVEfmt ', 8);
  h.writeUInt32LE(16, 16); h.writeUInt16LE(1, 20); h.writeUInt16LE(1, 22); h.writeUInt32LE(sr, 24);
  h.writeUInt32LE(sr * 2, 28); h.writeUInt16LE(2, 32); h.writeUInt16LE(16, 34); h.write('data', 36); h.writeUInt32LE(data.length, 40);
  writeFileSync(file, Buffer.concat([h, data]));
};
const ff = (args) => spawnSync('npx', ['remotion', 'ffmpeg', '-hide_banner', '-nostdin', '-y', ...args], {encoding: 'utf8'});
const meas = (file) => {
  const m = ff(['-i', file, '-af', 'loudnorm=I=-15:TP=-1.5:print_format=json', '-f', 'null', '-']);
  const j = /\{[^{}]*"input_i"[^{}]*\}/.exec(m.stderr || '');
  if (!j) fail(`could not measure loudness:\n${(m.stderr || '').slice(-800)}`);
  const o = JSON.parse(j[0]);
  return {i: Number(o.input_i), tp: Number(o.input_tp)};
};

const tmp = mkdtempSync(join(tmpdir(), 'sfx-whine-'));
try {
  const wav = join(tmp, 'whine.wav');
  writeWav(wav, 1);
  const d = meas(wav);
  const gain = 10 ** ((lufs - d.i) / 20);
  if (d.tp + (lufs - d.i) > -1.5) fail(`peak would exceed -1.5 dBTP at ${lufs} LUFS (${(d.tp + lufs - d.i).toFixed(2)}); lower --lufs`);
  writeWav(wav, gain);
  mkdirSync(dirname(outFile), {recursive: true});
  const r = ff(['-i', wav, '-c:a', 'libmp3lame', '-b:a', '128k', outFile]);
  if (r.status !== 0) fail(`ffmpeg failed:\n${(r.stderr || '').slice(-1500)}`);
  console.log(`wrote ${outFile} (target ${lufs} LUFS)`);
} finally {
  rmSync(tmp, {recursive: true, force: true});
}
