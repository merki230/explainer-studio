// Self-made car sounds for the drive-by-wire video: deterministic synths (no API, no cost).
//
// usage: yarn sfx:<kind> <slug> [--name <kind>] [--out <file>] [--seconds N] [--lufs L] [--from A] [--to B]
//        [--peak P] [--pitch X] [--clunk C] [--cyl 4|8] [--shifts N] [--idle S] [--dry] [--die]
//        (or: node scripts/sfx-drive.mjs <kind> <slug> ...)
//   kinds: engine | hiss | throttle | skid | thump | steer
//
// Every sound is modelled on the physical thing, with integer-ratio partials and filtered noise only:
//  engine    four-cylinder: 2 firings per revolution, so firing Hz = rpm/30. Harmonics of that (1/h^1.3)
//            plus a half-order lump (crank rev) and a little per-cycle level jitter, low-passed, over
//            intake noise. --from/--to = rpm (smoothstep between them), --peak = rpm the middle swells to
//            (sin^2 bump) for a rise-and-fall. Defaults: 6 s steady cruise at 1800 rpm, -20 LUFS.
//            idle: --from 800 --to 800; drop: --from 2200 --to 900; flare: --from 1200 --to 1200 --peak 4000 --seconds 2
//            V8: --cyl 8 (default 4; firing Hz = rpm*cyl/120). Cross-plane V8s fire unevenly, so it adds the
//            crank-revolution orders (rpm/60 x1..3) and more per-cycle jitter: the low burble, deeper.
//            Drag run: --shifts N (e.g. 7) builds idle (--idle s, default 1.5) -> rev to ~3000 -> launch ->
//            N upshifts at --peak rpm (default 6000, from-rpm = idle). Each shift lifts the throttle: rpm
//            falls to 70-82% of the shift rpm over 0.28 s with a level dip. Gears get longer. Length
//            --seconds (default 11 with --shifts). e.g. yarn sfx:engine <slug> --name v8-run --cyl 8 --shifts 7 --from 750
//  hiss      wet-road tire hiss: noise band-passed ~0.9-5 kHz plus faint road rumble, slow level wobble.
//            Loops seamlessly (end cross-faded into start). --pitch = speed (1 = 45 mph; filters scale).
//            --dry = dry asphalt roar: 0.4-2.2 kHz, more road rumble, no wet fizz. --from/--to (0.2-3) = speed
//            multiplier at start/end: a non-looping rise in pitch and level (--dry --from 0.6 --to 1.4 --seconds 10).
//            Defaults: 6 s, -24 LUFS. Louder in the skid scene: set the level in spec.ts.
//  throttle  throttle-body DC motor and gears, 0.25 s: tone sweeping --from..--to Hz (220 -> 480 = opens),
//            gear-mesh noise, and a soft plate-on-stop clunk (--clunk, 0 = off, default 0.35).
//            Snaps shut: --from 480 --to 160. Default -22 LUFS.
//  skid      wet tyre scrub: 0.5-3.5 kHz noise with a ~25 Hz stick-slip flutter, a hint of water sizzle,
//            no squeal. 1.4 s, -20 LUFS. --pitch scales the band.
//  thump     brake thump: a damped low body (95 -> 48 Hz) plus a short knock and pedal/caliper click.
//            0.6 s, -18 LUFS. --pitch scales the pitch.
//  steer     electric power-steering motor: speeds up and down over --seconds (0.9), tone --from..--to Hz
//            (150..330 at peak speed), partials x2 x3, faint gear whine, soft noise. -22 LUFS.
//  engine --die  (No. 009) gas engine at cruise that coughs and stalls, default 2.2 s: 0.3 s of cruise (1800 rpm, sagging),
//            then individual firings drop out (a seeded, growing misfire share, each with a muffled intake cough),
//            rpm and level fall away to nothing by ~2 s. --from sets the cruise rpm; --seconds >= 1.5.
//            e.g. yarn sfx:engine <slug> --name engine-die --die
// Mono 44.1 kHz, scaled to the target integrated loudness and checked to stay under -1.5 dBTP (the
// bundled ffmpeg has no limiter, so it fails rather than clips), encoded with Remotion's bundled ffmpeg
// (libmp3lame, 128k). Clips under 4 s are measured repeated back to back, i.e. the level while the sound
// plays. Same samples every run. Default output: out/<slug>/raw/sfx/<name>.mp3 (audition; never touches
// src/). Not logged in audio-log.md (nothing generated by a service).
import {spawnSync} from 'node:child_process';
import {mkdirSync, mkdtempSync, rmSync, writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {dirname, join} from 'node:path';

const KINDS = {
  engine: {seconds: 6, lufs: -20, from: 1800, to: 1800, fade: 0.3},
  hiss: {seconds: 6, lufs: -24, from: 0, to: 0, fade: 0},
  throttle: {seconds: 0.25, lufs: -22, from: 220, to: 480, fade: 0.01},
  skid: {seconds: 1.4, lufs: -20, from: 0, to: 0, fade: 0.05},
  thump: {seconds: 0.6, lufs: -18, from: 0, to: 0, fade: 0.1},
  steer: {seconds: 0.9, lufs: -22, from: 150, to: 330, fade: 0.08},
};
const usage = `yarn sfx:<${Object.keys(KINDS).join('|')}> <slug> [--name <kind>] [--out <file>] [--seconds N] [--lufs L]\n  [--from A] [--to B] [--peak P] [--pitch X] [--clunk C] [--cyl 4|8] [--shifts N] [--idle S] [--dry] [--die]`;
const fail = (msg) => {
  console.error(`${msg}\nusage: ${usage}`);
  process.exit(1);
};
const argv = process.argv.slice(2);
if (argv.includes('--help') || argv.includes('-h')) {
  console.log(`${usage}\n\n  Default output: out/<slug>/raw/sfx/<name>.mp3 (audition; never writes into src/).`);
  process.exit(0);
}
const opt = {name: '', out: '', seconds: '', lufs: '', from: '', to: '', peak: '0', pitch: '1', clunk: '0.35', cyl: '4', shifts: '0', idle: '1.5', dry: '', die: ''};
const flags = new Set(['dry', 'die']);
const pos = [];
for (let i = 0; i < argv.length; i++) {
  if (argv[i].startsWith('--') && flags.has(argv[i].slice(2))) opt[argv[i].slice(2)] = '1';
  else if (argv[i].startsWith('--') && argv[i].slice(2) in opt) opt[argv[i].slice(2)] = argv[++i] ?? '';
  else pos.push(argv[i]);
}
const [kind, slug] = pos;
const re = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;
if (!(kind in KINDS)) fail('first argument must be a kind');
const D = KINDS[kind];
const name = opt.name || kind;
if (!slug || pos.length > 2 || !re.test(slug) || !re.test(name)) fail('expected exactly one valid <slug> and a valid --name');
const num = (k, d) => (opt[k] === '' ? d : Number(opt[k]));
const shifts = Number(opt.shifts), cyl = Number(opt.cyl), idle = Number(opt.idle), dry = opt.dry === '1', die = opt.die === '1';
const seconds = num('seconds', kind === 'engine' && shifts > 0 ? 11 : die ? 2.2 : D.seconds), lufs = num('lufs', D.lufs), f0 = num('from', D.from), f1 = num('to', D.to);
const peakRpm = Number(opt.peak), pitch = Number(opt.pitch), clunk = Number(opt.clunk);
if (![seconds, lufs, f0, f1, peakRpm, pitch, clunk, shifts, cyl, idle].every(Number.isFinite) || !(seconds >= 0.1 && seconds <= 60) || !(lufs < 0 && lufs > -40) || pitch <= 0 || peakRpm < 0 || clunk < 0 || f0 < 0 || f1 < 0 || !Number.isInteger(shifts) || shifts < 0 || ![4, 8].includes(cyl) || idle < 0) fail('invalid option value (--cyl 4 or 8, --shifts integer)');
if (shifts > 0 && (kind !== 'engine' || seconds < idle + 0.9 + 0.58 * shifts + 0.3)) fail('--shifts is for engine and needs --seconds >= --idle + 1.2 + 0.58 x shifts');
if (die && (kind !== 'engine' || shifts > 0 || seconds < 1.5 || cyl !== 4)) fail('--die is for a four-cylinder engine without --shifts, --seconds >= 1.5');
if (kind === 'hiss' && (f0 || f1) && !(f0 >= 0.2 && f0 <= 3 && f1 >= 0.2 && f1 <= 3)) fail('hiss --from/--to are speed multipliers, 0.2-3 (both or neither)');
if (kind === 'engine' && (f0 < 300 || f1 < 300 || f0 > 8000 || f1 > 8000 || (peakRpm && peakRpm < 300))) fail('engine --from/--to/--peak are rpm, 300-8000');
if ((kind === 'throttle' || kind === 'steer') && (f0 < 50 || f1 < 50 || f0 > 3000 || f1 > 3000)) fail('--from/--to are Hz, 50-3000');
const outFile = opt.out || join('out', slug, 'raw', 'sfx', `${name}.mp3`);

const sr = 44100, n = Math.round(sr * seconds), TAU = 2 * Math.PI;
let seed = 31;
const rnd = () => ((seed = (seed * 1103515245 + 12345) & 0x7fffffff) / 0x7fffffff) * 2 - 1;
const noise = (len) => Float64Array.from({length: len}, rnd);
const lp = (x, fc, passes = 1) => {
  const a = 1 - Math.exp(-TAU * fc / sr), y = Float64Array.from(x);
  for (let p = 0; p < passes; p++) { let s = 0; for (let i = 0; i < y.length; i++) y[i] = s += a * (y[i] - s); }
  return y;
};
const hp = (x, fc, passes = 1) => { const l = lp(x, fc, passes); return x.map((v, i) => v - l[i]); };
const band = (x, lo, hi) => lp(hp(x, lo, 2), hi, 2);
const norm = (x) => { let m = 0; for (const v of x) m = Math.max(m, Math.abs(v)); return x.map((v) => v / (m || 1)); };
const smooth = (u) => u * u * (3 - 2 * u);

let z = new Float64Array(n);
if (kind === 'engine') {
  const jit = norm(lp(noise(n), cyl === 8 ? 9 : 6, 2)), nz = norm(lp(noise(n), 500, 2)), tone = new Float64Array(n);
  const rpmAt = new Float64Array(n).fill(0), gain = new Float64Array(n).fill(1);
  if (shifts > 0) { // idle, rev, launch, then N climbs separated by shift dips
    const peak = peakRpm || 6000, gap = 0.28, revT = 0.6, holdT = 0.3, ratio = (k) => 0.7 + 0.12 * (k / Math.max(1, shifts - 1));
    const gearT = seconds - idle - revT - holdT, wts = Array.from({length: shifts + 1}, (_, k) => 1 + 0.4 * k), wsum = wts.reduce((a, b) => a + b, 0);
    const segs = [], push = (t, r, g) => segs.push([t, r, g]);
    let t = 0;
    push(0, f0, 1); t += idle; push(t, f0, 1); t += revT; push(t, 3000, 1); t += holdT; push(t, 3000, 1);
    for (let k = 0; k <= shifts; k++) {
      t += Math.max(0.3, ((gearT - shifts * gap) * wts[k]) / wsum);
      push(t, k < shifts ? peak : peak * 0.97, 1);
      if (k < shifts) { const next = peak * ratio(k); push(t + gap * 0.5, (peak + next) / 2, 0.4); t += gap; push(t, next, 1); }
    }
    let j = 0;
    for (let i = 0; i < n; i++) {
      const ti = i / sr;
      while (j < segs.length - 2 && ti > segs[j + 1][0]) j++;
      const [t0, r0, g0] = segs[j], [t1, r1, g1] = segs[j + 1], u = Math.min(1, Math.max(0, (ti - t0) / Math.max(1e-6, t1 - t0)));
      const shiftSeg = g0 !== 1 || g1 !== 1, e = shiftSeg ? smooth(u) : u;
      rpmAt[i] = r0 + (r1 - r0) * e;
      gain[i] = g0 + (g1 - g0) * e;
      if (ti < idle + revT && ti >= idle) rpmAt[i] = r0 + (r1 - r0) * smooth(u);
    }
    const g2 = lp(gain, 25, 1);
    for (let i = 0; i < n; i++) gain[i] = g2[i];
  } else if (die) { // cruise, sag, misfires, then the rpm and level fall away
    for (let i = 0; i < n; i++) {
      const t = i / sr, c = Math.min(1, Math.max(0, (t - 0.3) / 0.6));
      rpmAt[i] = t < 0.9 ? f0 * (1 - 0.16 * smooth(c)) : f0 * 0.84 * Math.exp(-(t - 0.9) / 0.5);
      gain[i] = t < 1.1 ? 1 : Math.exp(-(t - 1.1) / 0.3);
    }
  } else {
    for (let i = 0; i < n; i++) {
      const u = i / (n - 1);
      let rpm = f0 + (f1 - f0) * smooth(u);
      if (peakRpm) rpm += (peakRpm - rpm) * Math.sin(Math.PI * u) ** 2;
      rpmAt[i] = rpm;
    }
  }
  let ph = 0, lastCyc = -1, burstT = 9, gate = 1, gateS = 1;
  const orders = cyl === 8 ? [[0.25, 0.5], [0.5, 0.4], [0.75, 0.3]] : [[0.5, 0.3]];
  for (let i = 0; i < n; i++) {
    const rpm = rpmAt[i], ff = (rpm * cyl) / 120;
    ph += TAU * ff / sr;
    let cough = 0;
    if (die) {
      const t = i / sr, cyc = Math.floor(ph / TAU / 1);
      if (cyc !== lastCyc) { // a new firing: seeded misfire chance grows from 0.3 s, ~70% by 1.2 s
        lastCyc = cyc;
        const h = Math.abs(Math.sin(cyc * 12.9898 + 4.1) * 43758.5453) % 1, pm = Math.min(0.72, Math.max(0, (t - 0.3) * 0.8));
        gate = h < pm ? 0.1 : 1;
        if (gate < 1) burstT = 0;
      }
      gateS += 0.08 * (gate - gateS);
      burstT += 1 / sr;
      cough = 2.2 * nz[i] * Math.exp(-burstT / 0.035) * Math.min(1, gain[i] * 3);
    }
    let s = 0;
    for (const [o, a] of orders) s += a * Math.sin(o * ph + 0.7);
    for (let h = 1; h * ff < (cyl === 8 ? 900 : 1400); h++) s += Math.sin(h * ph + h * 0.4) / h ** 1.3;
    const load = (0.55 + 0.45 * Math.min(1, rpm / 3500)) * gain[i];
    tone[i] = s * load * (die ? gateS : 1) * (1 + (cyl === 8 ? 0.25 : 0.12) * jit[i]) + 0.35 * nz[i] * load + cough;
  }
  z = lp(tone, cyl === 8 ? 550 : 700, 2);
} else if (kind === 'hiss') {
  const ramp = f0 > 0 && f1 > 0, xf = ramp ? 0 : Math.round(0.5 * sr), warm = 4410, len = n + xf + warm;
  const [lo, hi, rw] = dry ? [400, 2200, 0.8] : [900, 5000, 0.3];
  const layer = (sp) => {
    const h = norm(band(noise(len), lo * sp, hi * sp)), r = norm(lp(noise(len), (dry ? 250 : 200) * sp, 2));
    return h.map((v, i) => v + rw * r[i]);
  };
  const wob = norm(lp(noise(len), 2, 2));
  const x = new Float64Array(n + xf);
  if (ramp) {
    const A = layer(pitch * f0), B = layer(pitch * f1);
    for (let i = 0; i < n; i++) {
      const u = i / (n - 1), e = smooth(u);
      x[i] = (A[i + warm] * (1 - e) + B[i + warm] * e) * (0.45 + 0.55 * e) * (1 + 0.1 * wob[i + warm]);
    }
  } else {
    const A = layer(pitch);
    for (let i = 0; i < n + xf; i++) x[i] = A[i + warm] * (1 + 0.1 * wob[i + warm]);
  }
  for (let i = 0; i < n; i++) z[i] = i < xf ? x[i] * Math.sin(0.5 * Math.PI * i / xf) + x[n + i] * Math.cos(0.5 * Math.PI * i / xf) : x[i];
} else if (kind === 'throttle') {
  const gear = band(noise(n), 1000, 3000);
  let ph = 0;
  for (let i = 0; i < n; i++) {
    const t = i / sr, u = i / (n - 1), f = f0 + (f1 - f0) * smooth(u);
    ph += TAU * f / sr;
    const env = Math.min(1, t / 0.012) * (u > 0.75 ? Math.cos(0.5 * Math.PI * (u - 0.75) / 0.25) : 1);
    z[i] = env * (Math.sin(ph) + 0.5 * Math.sin(2 * ph) + 0.3 * Math.sin(3 * ph) + 0.8 * gear[i] * (0.6 + 0.4 * Math.sin(5 * ph)));
  }
  if (clunk > 0) { // plate meeting its stop, near the end
    const c0 = Math.round(n * 0.78);
    for (let i = c0; i < n; i++) { const t = (i - c0) / sr; z[i] += clunk * 3 * Math.sin(TAU * 140 * t) * Math.exp(-t / 0.012); }
  }
  z = lp(z, 4000, 2);
} else if (kind === 'skid') {
  const scrub = band(noise(n), 500 * pitch, 3500 * pitch), fizz = band(noise(n), 4000, 8000), flut = norm(lp(noise(n), 25, 2));
  for (let i = 0; i < n; i++) {
    const t = i / sr, env = Math.min(1, t / 0.15) * Math.min(1, (seconds - t) / 0.4);
    z[i] = env * (scrub[i] * (0.65 + 0.35 * flut[i]) * 6 + 0.25 * fizz[i] * 6 * (0.7 + 0.3 * flut[i]));
  }
  z = lp(z, 6000, 1);
} else if (kind === 'thump') {
  const click = lp(noise(n), 2000, 1);
  let ph = 0;
  for (let i = 0; i < n; i++) {
    const t = i / sr, f = (48 + 47 * Math.exp(-t / 0.03)) * pitch;
    ph += TAU * f / sr;
    z[i] = Math.min(1, t / 0.002) * (Math.sin(ph) * Math.exp(-t / 0.09) + 0.4 * Math.sin(TAU * 180 * pitch * t) * Math.exp(-t / 0.02) + 6 * click[i] * Math.exp(-t / 0.004));
  }
  z = lp(z, 1000, 2);
} else {
  const nz = band(noise(n), 600, 2000);
  let ph = 0;
  for (let i = 0; i < n; i++) {
    const u = i / (n - 1), s = Math.sin(Math.PI * u) ** 0.7, f = f0 + (f1 - f0) * s;
    ph += TAU * f / sr;
    z[i] = (0.2 + 0.8 * s) * (Math.sin(ph) + 0.45 * Math.sin(2 * ph) + 0.25 * Math.sin(3 * ph) + 0.08 * Math.sin(5.5 * ph) + 12 * nz[i] * 0.3);
  }
  z = lp(z, 3500, 2);
}
{
  let pk = 0;
  for (let i = 0; i < n; i++) pk = Math.max(pk, Math.abs(z[i]));
  for (let i = 0; i < n; i++) z[i] *= 0.3 / pk;
  const fade = Math.min(Math.round((kind === 'hiss' && f0 > 0 && f1 > 0 ? 0.15 : D.fade) * sr), n >> 1);
  for (let i = 0; i < fade; i++) { const g = Math.sin(0.5 * Math.PI * i / fade); z[i] *= g; z[n - 1 - i] *= g; }
}

const writeWav = (file, gain, reps = 1) => {
  const pcm = new Int16Array(n * reps);
  for (let r = 0; r < reps; r++) for (let i = 0; i < n; i++) pcm[r * n + i] = Math.round(Math.max(-1, Math.min(1, z[i] * gain)) * 32767);
  const data = Buffer.from(pcm.buffer), h = Buffer.alloc(44);
  h.write('RIFF', 0); h.writeUInt32LE(36 + data.length, 4); h.write('WAVEfmt ', 8);
  h.writeUInt32LE(16, 16); h.writeUInt16LE(1, 20); h.writeUInt16LE(1, 22); h.writeUInt32LE(sr, 24);
  h.writeUInt32LE(sr * 2, 28); h.writeUInt16LE(2, 32); h.writeUInt16LE(16, 34); h.write('data', 36); h.writeUInt32LE(data.length, 40);
  writeFileSync(file, Buffer.concat([h, data]));
};
const ff = (args) => spawnSync('npx', ['remotion', 'ffmpeg', '-hide_banner', '-nostdin', '-y', ...args], {encoding: 'utf8'});
const meas = (file) => {
  const m = ff(['-i', file, '-af', 'loudnorm=I=-15:TP=-1.5:print_format=json', '-f', 'null', '-']);
  const j = /\{[^{}]*"input_i"[^{}]*\}/.exec(m.stderr || '');
  if (!j) fail(`could not measure loudness:\n${(m.stderr || '').slice(-800)}`);
  const o = JSON.parse(j[0]);
  return {i: Number(o.input_i), tp: Number(o.input_tp)};
};

const tmp = mkdtempSync(join(tmpdir(), `sfx-${kind}-`));
try {
  const reps = Math.max(1, Math.ceil(4 / seconds)), wav = join(tmp, `${kind}.wav`);
  writeWav(wav, 1, reps);
  const d = meas(wav), gain = 10 ** ((lufs - d.i) / 20);
  if (d.tp + (lufs - d.i) > -1.5) fail(`peak would exceed -1.5 dBTP at ${lufs} LUFS (${(d.tp + lufs - d.i).toFixed(2)}); lower --lufs`);
  writeWav(wav, gain);
  mkdirSync(dirname(outFile), {recursive: true});
  const r = ff(['-i', wav, '-c:a', 'libmp3lame', '-b:a', '128k', outFile]);
  if (r.status !== 0) fail(`ffmpeg failed:\n${(r.stderr || '').slice(-1500)}`);
  console.log(`wrote ${outFile} (${kind}, target ${lufs} LUFS)`);
} finally {
  rmSync(tmp, {recursive: true, force: true});
}
